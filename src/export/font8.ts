/**
 * Tiny 8x8 bitmap font for the mock AGI status and input lines.
 * Each glyph is 8 rows of 8 bits (MSB = leftmost pixel).
 */
const G: Record<string, number[]> = {
  ' ': [0, 0, 0, 0, 0, 0, 0, 0],
  S: [0x7c, 0xc6, 0xc0, 0x7c, 0x06, 0xc6, 0x7c, 0x00],
  c: [0x00, 0x00, 0x7c, 0xc6, 0xc0, 0xc6, 0x7c, 0x00],
  o: [0x00, 0x00, 0x7c, 0xc6, 0xc6, 0xc6, 0x7c, 0x00],
  r: [0x00, 0x00, 0xdc, 0x76, 0x60, 0x60, 0xf0, 0x00],
  e: [0x00, 0x00, 0x7c, 0xc6, 0xfe, 0xc0, 0x7c, 0x00],
  f: [0x1c, 0x36, 0x30, 0x78, 0x30, 0x30, 0x78, 0x00],
  u: [0x00, 0x00, 0xcc, 0xcc, 0xcc, 0xcc, 0x76, 0x00],
  n: [0x00, 0x00, 0xdc, 0x66, 0x66, 0x66, 0x66, 0x00],
  d: [0x1c, 0x0c, 0x7c, 0xcc, 0xcc, 0xcc, 0x76, 0x00],
  ':': [0x00, 0x30, 0x30, 0x00, 0x00, 0x30, 0x30, 0x00],
  '>': [0x60, 0x30, 0x18, 0x0c, 0x18, 0x30, 0x60, 0x00],
  _: [0, 0, 0, 0, 0, 0, 0, 0xff],
  '0': [0x7c, 0xc6, 0xce, 0xde, 0xf6, 0xe6, 0x7c, 0x00],
  '1': [0x30, 0x70, 0x30, 0x30, 0x30, 0x30, 0xfc, 0x00],
  '5': [0xfe, 0xc0, 0xfc, 0x06, 0x06, 0xc6, 0x7c, 0x00],
  '8': [0x7c, 0xc6, 0xc6, 0x7c, 0xc6, 0xc6, 0x7c, 0x00],
}

/** Draw text into a 320-wide EGA index buffer at pixel (x, y). */
export function drawText(buf: Uint8Array, width: number, text: string, x: number, y: number, color: number): void {
  for (let n = 0; n < text.length; n++) {
    const g = G[text[n]] ?? G[' ']
    for (let row = 0; row < 8; row++) {
      for (let bit = 0; bit < 8; bit++) {
        if (g[row] & (0x80 >> bit)) buf[(y + row) * width + x + n * 8 + bit] = color
      }
    }
  }
}
